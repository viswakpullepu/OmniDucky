"""
Natural Language to DuckyScript Engine (Refined & Trained)
=========================================================
Advanced semantic intent classifier and parser that translates arbitrary
human natural language instructions into synchronized, platform-adapted
DuckyScript payloads for Windows, Android, iOS, macOS, and Linux.

Features:
  - Multi-intent compound sentence splitting (delays, connectors, steps)
  - Typo tolerance and synonym expansion
  - Operating-system-aware shortcuts (Spotlight vs Run Dialog vs evdev)
  - Productivity & Window Management (copy, paste, save, select-all, close, switch)
  - Permission dialog auto-navigation (dual Tab + Calibrated Screen % Tap)
  - Media & System controls (volume, home, screenshot, lock)
"""

import re
from typing import List, Dict, Any, Tuple

# Common application aliases & typo auto-corrections
APP_ALIASES = {
    "notepd": "notepad",
    "notes": "notes",
    "textedit": "textedit",
    "chrom": "chrome",
    "chroome": "chrome",
    "google chrome": "chrome",
    "safri": "safari",
    "edge": "msedge",
    "edg": "msedge",
    "microsoft edge": "msedge",
    "firefox": "firefox",
    "calc": "calc",
    "calculator": "calc",
    "claculator": "calc",
    "calcultor": "calc",
    "powrshell": "powershell",
    "posh": "powershell",
    "terminal": "terminal",
    "cmd": "cmd",
    "command prompt": "cmd",
    "explorer": "explorer",
    "explorr": "explorer",
    "explor": "explorer",
    "settings": "settings",
    "youtube": "https://www.youtube.com",
    "google": "https://www.google.com",
}


class NaturalLanguageToDucky:
    """Trained semantic parser translating human language into valid DuckyScript."""

    def __init__(self):
        pass

    def convert(self, prompt: str, target_os: str = "windows", screen_res: str = "1080 2400") -> Dict[str, Any]:
        """Convert natural language instructions to complete DuckyScript."""
        lines = [line.strip() for line in prompt.splitlines() if line.strip()]
        target_os = target_os.lower()

        ducky_lines: List[str] = [
            f"REM Auto-generated by OmniDucky Refined NLP Engine",
            f"REM Target Platform: {target_os.capitalize()}",
            "DEFAULT_DELAY 80",
            "DELAY 1000",
            ""
        ]

        steps_translated = []
        flattened_actions = []

        for raw_line in lines:
            # Strip list numbers e.g. "1. ", "Step 1: ", "- "
            clean_line = re.sub(r'^(?:step\s*\d+[:.]?|\d+[\.\)]|\*|-)\s*', '', raw_line, flags=re.IGNORECASE).strip()
            if not clean_line:
                continue

            # Split compound actions while preserving URLs and decimals
            parts = re.split(r'\b(?:and\s+then|then|after\s+that|next|and\s+(?=wait|type|run|save|close|press|click|left|right|go|browse|lock|hit|execute|copy|paste|move|jiggle|take))\b|(?<!\w\.\w)(?<=\s)\.|\.(?=\s+[A-Z]|\s*$)', clean_line, flags=re.IGNORECASE)
            for part in parts:
                if part:
                    p = part.strip()
                    if p:
                        flattened_actions.append(p)

        for action in flattened_actions:
            translated, desc = self._translate_action(action, target_os)
            if translated:
                ducky_lines.append(f"REM {desc}")
                ducky_lines.extend(translated)
                ducky_lines.append("")
                steps_translated.append(desc)

        script_text = "\n".join(ducky_lines).strip() + "\n"
        return {
            "success": True,
            "script": script_text,
            "steps": steps_translated,
            "count": len(steps_translated)
        }

    def _translate_action(self, text: str, target_os: str) -> Tuple[List[str], str]:
        t = text.strip()
        lower_t = t.lower()

        # -------------------------------------------------------------
        # 1. Delays, Sleep, Pause, Wait
        # -------------------------------------------------------------
        if re.search(r'\b(?:wait|delay|sleep|pause|hold)\b', lower_t):
            # "wait a second" / "wait a moment"
            if re.search(r'\b(?:a\s+second|a\s+sec|a\s+moment|a\s+bit)\b', lower_t):
                return ["DELAY 1000"], "Wait 1000ms"

            m = re.search(r'(\d+(?:\.\d+)?)\s*(seconds?|secs?|s|milliseconds?|ms)?', lower_t)
            if m:
                val = float(m.group(1))
                unit = (m.group(2) or 'seconds').lower()
                ms = int(val * 1000) if 's' in unit and 'm' not in unit else int(val)
                return [f"DELAY {ms}"], f"Wait {ms}ms"
            return ["DELAY 1000"], "Wait 1000ms (default pause)"

        # -------------------------------------------------------------
        # 2. Open / Browse to URL
        # -------------------------------------------------------------
        url_match = re.search(r'(?:https?://[^\s]+|www\.[^\s]+|[a-zA-Z0-9-]+\.(?:com|org|net|io|edu|gov|app|dev|ai|me)(?:/[^\s]*)?)', t, re.IGNORECASE)
        if url_match and any(w in lower_t for w in ("open", "go to", "browse", "visit", "url", "site", "web")):
            url = url_match.group(0)
            if not url.startswith('http://') and not url.startswith('https://'):
                url = 'https://' + url

            if target_os in ("android", "ios"):
                return [
                    "GUI SPACE",
                    "DELAY 800",
                    f"STRING {url}",
                    "ENTER"
                ], f"Launch URL on mobile: {url}"
            elif target_os == "mac":
                return [
                    "GUI SPACE",
                    "DELAY 600",
                    f"STRING {url}",
                    "ENTER"
                ], f"Launch URL via Spotlight: {url}"
            else:
                return [
                    "GUI r",
                    "DELAY 500",
                    f"STRING {url}",
                    "ENTER"
                ], f"Launch URL in browser: {url}"

        # -------------------------------------------------------------
        # 3. Terminal & Shell Commands
        # -------------------------------------------------------------
        if re.search(r'\b(?:open|launch|start|pull\s*up)\s*(?:powershell|terminal|cmd|command\s*prompt|bash|shell)\b', lower_t):
            if target_os == "mac":
                return ["GUI SPACE", "DELAY 500", "STRING Terminal", "ENTER", "DELAY 1000"], "Launch macOS Terminal"
            elif target_os == "linux":
                return ["CTRL ALT t", "DELAY 800"], "Launch Linux Terminal"
            else:
                shell = "powershell" if "powershell" in lower_t else "cmd"
                return ["GUI r", "DELAY 500", f"STRING {shell}", "ENTER", "DELAY 1000"], f"Launch Windows {shell.upper()}"

        run_cmd = re.search(r'(?:run|execute|type\s*in\s*terminal)\s*(?:command)?:?\s*["\']?([^"\']+)["\']?$', t, re.IGNORECASE)
        if run_cmd and any(k in lower_t for k in ("run", "execute")):
            cmd = run_cmd.group(1).strip()
            return [f"STRINGLN {cmd}"], f"Execute command: {cmd}"

        # -------------------------------------------------------------
        # 4. Open Applications (Smart typo & platform resolution)
        # -------------------------------------------------------------
        app_match = re.search(r'\b(?:open|launch|start|fire\s*up|pull\s*up)\s+([a-zA-Z0-9\s_-]+)$', lower_t)
        if app_match and not any(k in lower_t for k in ("url", "link", "website", "mouse", "dialog")):
            raw_app = app_match.group(1).strip()
            resolved_app = APP_ALIASES.get(raw_app, raw_app)

            if target_os in ("android", "ios"):
                return [
                    "GUI SPACE",
                    "DELAY 700",
                    f"STRING {resolved_app}",
                    "DELAY 400",
                    "ENTER"
                ], f"Search & open {resolved_app} on mobile"
            elif target_os == "mac":
                return [
                    "GUI SPACE",
                    "DELAY 600",
                    f"STRING {resolved_app}",
                    "ENTER",
                    "DELAY 800"
                ], f"Open {resolved_app} via Spotlight"
            else:
                return [
                    "GUI r",
                    "DELAY 500",
                    f"STRING {resolved_app}",
                    "ENTER",
                    "DELAY 800"
                ], f"Launch application: {resolved_app}"

        # -------------------------------------------------------------
        # 5. Permission Modals & Dialog Handling
        # -------------------------------------------------------------
        if re.search(r'\b(?:click\s*allow|allow\s*permission|grant\s*permission|click\s*ok|accept\s*permission|dismiss\s*popup|confirm)\b', lower_t):
            if target_os in ("android", "ios"):
                return [
                    "REM Focus navigation to affirmative modal button",
                    "TAB",
                    "DELAY 200",
                    "TAB",
                    "DELAY 200",
                    "ENTER",
                    "REM Calibrated adaptive screen tap (center-lower modal)",
                    "MOUSE_POS_PCT 50 62",
                    "DELAY 150",
                    "MOUSE_CLICK LEFT"
                ], "Auto-accept permission prompt (Tab Focus + Calibrated Screen % Tap)"
            else:
                return ["ENTER"], "Confirm dialog via Enter"

        # -------------------------------------------------------------
        # 6. Mouse Actions (Positions, Clicks, Drags, Jigglers)
        # -------------------------------------------------------------
        pct_click = re.search(r'\b(?:click|tap)\s*(?:at)?\s*(\d+(?:\.\d+)?)\s*%\s*(?:and|,)?\s*(\d+(?:\.\d+)?)\s*%', lower_t)
        if pct_click:
            px = float(pct_click.group(1))
            py = float(pct_click.group(2))
            return [f"MOUSE_POS_PCT {px} {py}", "DELAY 100", "MOUSE_CLICK LEFT"], f"Adaptive tap at {px}% X, {py}% Y"

        if re.search(r'\b(?:click|tap)\s*(?:the\s*)?center\b', lower_t):
            return ["MOUSE_POS_PCT 50 50", "DELAY 100", "MOUSE_CLICK LEFT"], "Adaptive tap at screen center (50%, 50%)"

        if re.search(r'\b(?:double\s*click)\b', lower_t):
            return ["MOUSE_CLICK LEFT", "DELAY 100", "MOUSE_CLICK LEFT"], "Mouse Double Click"

        if re.search(r'\b(?:right\s*click)\b', lower_t):
            return ["MOUSE_CLICK RIGHT"], "Mouse Right Click"

        if re.search(r'\b(?:left\s*click|click\s*mouse|single\s*click)\b', lower_t) or lower_t in ("click", "tap"):
            return ["MOUSE_CLICK LEFT"], "Mouse Left Click"

        mm_xy = re.search(r'\b(?:move\s*(?:mouse|cursor)|cursor|mouse)\s*(?:by|to)?\s*(-?\d+)\s*[, ]\s*(-?\d+)', lower_t)
        if mm_xy:
            mx, my = int(mm_xy.group(1)), int(mm_xy.group(2))
            return [f"MOUSE_MOVE {mx} {my}"], f"Move mouse delta ({mx}, {my})"

        mm_dir = re.search(r'\b(?:move\s*(?:mouse|cursor)|scroll)\s*(?:to\s*the)?\s*(down|up|left|right)\s*(?:by)?\s*(\d+)?', lower_t)
        if mm_dir:
            direction = mm_dir.group(1).lower()
            amt = int(mm_dir.group(2)) if mm_dir.group(2) else 100
            dx, dy = (0, amt) if direction == "down" else ((0, -amt) if direction == "up" else ((amt, 0) if direction == "right" else (-amt, 0)))
            return [f"MOUSE_MOVE {dx} {dy}"], f"Move mouse {direction} by {amt}px"

        if re.search(r'\b(?:jiggle\s*mouse|mouse\s*jiggler|prevent\s*sleep)\b', lower_t):
            return [
                "MOUSE_MOVE 40 -40",
                "DELAY 40",
                "MOUSE_MOVE -40 40",
                "DELAY 40"
            ], "Anti-sleep kinetic mouse jiggle"

        # -------------------------------------------------------------
        # 7. Common Productivity & Window Shortcuts
        # -------------------------------------------------------------
        mod = "GUI" if target_os in ("mac", "ios") else "CTRL"
        if re.search(r'\b(?:copy\s*(?:text|that)?|press\s*ctrl\+c)\b', lower_t):
            return [f"{mod} c"], "Copy (Clipboard)"
        if re.search(r'\b(?:paste\s*(?:text|that)?|press\s*ctrl\+v)\b', lower_t):
            return [f"{mod} v"], "Paste (Clipboard)"
        if re.search(r'\b(?:select\s*all)\b', lower_t):
            return [f"{mod} a"], "Select All"
        if re.search(r'\b(?:save\s*(?:file|document)?)\b', lower_t):
            return [f"{mod} s"], "Save"
        if re.search(r'\b(?:undo)\b', lower_t):
            return [f"{mod} z"], "Undo"
        if re.search(r'\b(?:switch\s*apps?|app\s*switcher|alt\s*tab)\b', lower_t):
            return ["GUI TAB" if target_os in ("mac", "ios") else "ALT TAB"], "Switch App (Task Switcher)"
        if re.search(r'\b(?:close\s*(?:window|tab|app)|quit\s*app|exit\s*app)\b', lower_t):
            return ["GUI w" if target_os in ("mac", "ios") else "CTRL w"], "Close Active Window/Tab"

        # -------------------------------------------------------------
        # 8. System Controls & Hotkeys
        # -------------------------------------------------------------
        if re.search(r'\b(?:lock\s*(?:the)?\s*(?:pc|screen|computer)|lock\s*screen)\b', lower_t):
            return ["GUI l"], "Lock Screen"
        if re.search(r'\b(?:show\s*desktop|minimize\s*all)\b', lower_t):
            return ["GUI d"], "Minimize All / Show Desktop"
        if re.search(r'\b(?:take\s*(?:a)?\s*screenshot|screenshot|screen\s*capture)\b', lower_t):
            return ["GUI SHIFT s" if target_os == "windows" else ("GUI SHIFT 3" if target_os == "mac" else "PRINTSCREEN")], "Capture Screenshot"
        if re.search(r'\b(?:go\s*home|home\s*screen|press\s*home)\b', lower_t):
            return ["GUI h" if target_os in ("ios", "android") else "GUI d"], "Navigate to Home Screen"

        # Single key presses
        if re.search(r'\b(?:press|hit)\s+(?:enter|return)\b', lower_t) or lower_t in ("enter", "return"):
            return ["ENTER"], "Press Enter"
        if re.search(r'\b(?:press|hit)\s+(?:tab)\b', lower_t) or lower_t == "tab":
            return ["TAB"], "Press Tab"
        if re.search(r'\b(?:press|hit)\s+(?:esc|escape)\b', lower_t) or lower_t in ("esc", "escape"):
            return ["ESCAPE"], "Press Escape"
        if re.search(r'\b(?:press|hit)\s+(?:space|spacebar)\b', lower_t) or lower_t in ("space", "spacebar"):
            return ["SPACE"], "Press Space"

        # Explicit hotkey combos like "press win+r", "press ctrl+shift+esc", "press alt+f4"
        combo_match = re.search(r'\b(?:press|hotkey|keys?)\s+([a-zA-Z0-9\+\s]+)', t, re.IGNORECASE)
        if combo_match:
            raw_combo = combo_match.group(1).replace("+", " ").strip().upper()
            return [raw_combo], f"Press combo: {raw_combo}"

        # -------------------------------------------------------------
        # 9. Typing & Text Injection
        # -------------------------------------------------------------
        type_match = re.search(r'\b(?:type|write|input|enter\s*text|inject)\s*(?:the\s*text)?\s*[:\'"]?\s*(.+?)[\'"]?$', t, re.IGNORECASE)
        if type_match:
            text_val = type_match.group(1).strip().strip('"\'')
            if "and press enter" in lower_t or "with enter" in lower_t:
                text_val = re.sub(r'\s+and\s+press\s+enter.*$', '', text_val, flags=re.IGNORECASE).strip()
                return [f"STRINGLN {text_val}"], f"Type with Enter: '{text_val}'"
            return [f"STRING {text_val}"], f"Type text: '{text_val}'"

        # -------------------------------------------------------------
        # 10. Default Fallback: Treat as typing
        # -------------------------------------------------------------
        return [f"STRING {t}"], f"Type text: '{t}'"
