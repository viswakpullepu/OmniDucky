class BleGenerator:
    """Generate an ESP32-S3 Arduino sketch using BLE HID keyboard."""

    HEADER = '''\
/*
 * ESP32-S3 Bluetooth Rubber Ducky
 * Auto-generated by esp32-ducky toolkit
 *
 * IMPORTANT: For authorized security testing and education ONLY.
 *
 * Mode:   Bluetooth Low Energy (BLE) HID Keyboard
 * Pairs with: Android, iOS, Windows, macOS, Linux
 *
 * SETUP:
 *   1. Install library: Sketch > Include Library > Manage Libraries
 *      Search "ESP32 BLE Keyboard" by T-vK -> Install
 *   2. Flash this sketch to your ESP32-S3
 *   3. On the target device, open Bluetooth settings
 *   4. Pair with "{device_name}"
 *   5. Payload executes automatically after pairing
 *   6. Press BOOT button (GPIO 0) to re-run payload
 */

#include <BleKeyboard.h>

// ---- CONFIGURATION ----
// Change these to blend in on the target's Bluetooth list
#define DEVICE_NAME     "{device_name}"
#define DEVICE_MANUFACTURER "Microsoft"
#define BATTERY_LEVEL   80

BleKeyboard bleKeyboard(DEVICE_NAME, DEVICE_MANUFACTURER, BATTERY_LEVEL);

#ifndef LED_BUILTIN
#define LED_BUILTIN 2
#endif

#define TRIGGER_PIN 0

bool payloadExecuted = false;

void setup() {{
  Serial.begin(115200);
  pinMode(LED_BUILTIN, OUTPUT);
  pinMode(TRIGGER_PIN, INPUT_PULLUP);

  Serial.println("[*] Starting BLE Keyboard...");
  Serial.println("[*] Device name: {device_name}");

  bleKeyboard.begin();

  // Blink while waiting for connection
  Serial.println("[*] Waiting for BLE connection...");
}}

void loop() {{
  if (bleKeyboard.isConnected()) {{
    if (!payloadExecuted) {{
      Serial.println("[+] Device connected! Executing payload...");
      // Brief delay after connection for device readiness
      delay(1000);
      digitalWrite(LED_BUILTIN, HIGH);

      executePayload();

      digitalWrite(LED_BUILTIN, LOW);
      payloadExecuted = true;
      Serial.println("[+] Payload complete.");

      // Blink 3 times to signal completion
      for (int i = 0; i < 3; i++) {{
        digitalWrite(LED_BUILTIN, HIGH);
        delay(100);
        digitalWrite(LED_BUILTIN, LOW);
        delay(100);
      }}
    }}

    // Re-trigger on button press
    if (digitalRead(TRIGGER_PIN) == LOW) {{
      delay(500);
      Serial.println("[*] Re-running payload...");
      executePayload();
      payloadExecuted = true;
      delay(2000);
    }}
  }} else {{
    // Blink slowly while waiting for connection
    payloadExecuted = false;
    digitalWrite(LED_BUILTIN, HIGH);
    delay(200);
    digitalWrite(LED_BUILTIN, LOW);
    delay(800);
  }}
}}

void typeString(const char* str) {{
  for (int i = 0; str[i] != '\\0'; i++) {{
    bleKeyboard.press(str[i]);
    delay(8);
    bleKeyboard.release(str[i]);
    delay(8);
  }}
}}

void bleMoveToScreenPercent(float pctX, float pctY, int screenW, int screenH) {
  // 1. Reset cursor to top-left corner (0, 0)
  for (int i = 0; i < 25; i++) {
    bleMouse.move(-120, -120);
    delay(5);
  }
  delay(100);

  // 2. Calculate target pixels from calibrated resolution
  int targetX = (int)((pctX / 100.0f) * screenW);
  int targetY = (int)((pctY / 100.0f) * screenH);

  // 3. Step towards target coordinates in safe increments
  while (targetX > 0 || targetY > 0) {
    int stepX = (targetX > 100) ? 100 : targetX;
    int stepY = (targetY > 100) ? 100 : targetY;
    bleMouse.move(stepX, stepY);
    targetX -= stepX;
    targetY -= stepY;
    delay(5);
  }
  delay(50);
}

void executePayload() {{
'''

    FOOTER = '''\
}
'''

    def __init__(self, device_name: str = "Wireless Keyboard"):
        self.indent = "  "
        self.device_name = device_name

    def generate(self, commands: List[Command], default_delay: int = 0) -> str:
        """Generate complete BLE Arduino sketch from command list."""
        has_mouse = any(c.cmd_type in ("mouse_move", "mouse_click", "mouse_scroll", "mouse_pos_pct") for c in commands)

        lines = []
        header = self.HEADER.replace("{device_name}", self.device_name)
        if has_mouse:
            header = header.replace(
                '#include <BleKeyboard.h>',
                '#include <BleKeyboard.h>\n#include <BleMouse.h>\n\n// Note: Install "ESP32 BLE Mouse" by T-vK from Arduino Library Manager'
            )
            header = header.replace(
                'BleKeyboard bleKeyboard(DEVICE_NAME, DEVICE_MANUFACTURER, BATTERY_LEVEL);',
                'BleKeyboard bleKeyboard(DEVICE_NAME, DEVICE_MANUFACTURER, BATTERY_LEVEL);\nBleMouse bleMouse(DEVICE_NAME, DEVICE_MANUFACTURER, BATTERY_LEVEL);'
            )
            header = header.replace(
                'bleKeyboard.begin();',
                'bleKeyboard.begin();\n  bleMouse.begin();'
            )
        lines.append(header)

        screen_w = 1080
        screen_h = 2400
        prev_cmd = None

        for cmd in commands:
            if default_delay > 0 and prev_cmd is not None:
                lines.append(f"{self.indent}delay({default_delay});")

            lines.append(f"{self.indent}// Line {cmd.line_num}: {cmd.cmd_type}")

            if cmd.cmd_type == "screen_size":
                screen_w = cmd.mouse_x
                screen_h = cmd.mouse_y
                lines.append(f"{self.indent}// Screen resolution set to {screen_w}x{screen_h}")
                lines.append("")

            elif cmd.cmd_type == "mouse_pos_pct":
                parts = cmd.value.split(",")
                px = float(parts[0])
                py = float(parts[1])
                lines.append(f"{self.indent}bleMoveToScreenPercent({px}f, {py}f, {screen_w}, {screen_h});")
                lines.append("")

            if cmd.cmd_type == "delay":
                lines.append(f"{self.indent}delay({cmd.delay_ms});")
                lines.append("")

            elif cmd.cmd_type == "mouse_move":
                lines.append(f"{self.indent}bleMouse.move({cmd.mouse_x}, {cmd.mouse_y});")
                lines.append(f"{self.indent}delay(20);")
                lines.append("")

            elif cmd.cmd_type == "mouse_click":
                btn = "MOUSE_LEFT" if cmd.mouse_button == "LEFT" else ("MOUSE_RIGHT" if cmd.mouse_button == "RIGHT" else "MOUSE_MIDDLE")
                lines.append(f"{self.indent}bleMouse.click({btn});")
                lines.append(f"{self.indent}delay(50);")
                lines.append("")

            elif cmd.cmd_type == "mouse_scroll":
                lines.append(f"{self.indent}bleMouse.move(0, 0, {cmd.mouse_wheel});")
                lines.append(f"{self.indent}delay(30);")
                lines.append("")

            elif cmd.cmd_type == "default_delay":
                default_delay = cmd.delay_ms
                lines.append(f"{self.indent}// Default delay set to {cmd.delay_ms}ms")
                lines.append("")

            elif cmd.cmd_type == "string":
                escaped = self._escape_string(cmd.value)
                lines.append(f'{self.indent}typeString("{escaped}");')
                lines.append("")

            elif cmd.cmd_type == "stringln":
                escaped = self._escape_string(cmd.value)
                lines.append(f'{self.indent}typeString("{escaped}");')
                lines.append(f"{self.indent}bleKeyboard.press(KEY_RETURN);")
                lines.append(f"{self.indent}delay(10);")
                lines.append(f"{self.indent}bleKeyboard.release(KEY_RETURN);")
                lines.append("")

            elif cmd.cmd_type == "keypress":
                for key in cmd.keys:
                    key_const = self._resolve_key(key)
                    lines.append(f"{self.indent}bleKeyboard.press({key_const});")
                lines.append(f"{self.indent}delay(30);")
                for key in reversed(cmd.keys):
                    key_const = self._resolve_key(key)
                    lines.append(f"{self.indent}bleKeyboard.release({key_const});")
                lines.append("")

            elif cmd.cmd_type == "combo":
                for mod in cmd.modifiers:
                    mod_const = BLE_MODIFIERS[mod]
                    lines.append(f"{self.indent}bleKeyboard.press({mod_const});")
                for key in cmd.keys:
                    key_const = self._resolve_key(key)
                    lines.append(f"{self.indent}bleKeyboard.press({key_const});")
                lines.append(f"{self.indent}delay(30);")
                for key in reversed(cmd.keys):
                    key_const = self._resolve_key(key)
                    lines.append(f"{self.indent}bleKeyboard.release({key_const});")
                for mod in reversed(cmd.modifiers):
                    mod_const = BLE_MODIFIERS[mod]
                    lines.append(f"{self.indent}bleKeyboard.release({mod_const});")
                lines.append("")

            elif cmd.cmd_type == "repeat":
                if prev_cmd:
                    lines.append(
                        f"{self.indent}// Repeat previous command {cmd.repeat_count} more time(s)"
                    )
                    repeat_code = self._generate_single(prev_cmd)
                    lines.append(
                        f"{self.indent}for (int _r = 0; _r < {cmd.repeat_count}; _r++) {{"
                    )
                    for rc in repeat_code:
                        lines.append(f"{self.indent}  {rc}")
                    lines.append(f"{self.indent}}}")
                lines.append("")

            prev_cmd = cmd

        lines.append(self.FOOTER)
        return "\n".join(lines)

    def _generate_single(self, cmd: Command) -> List[str]:
        """Generate code lines for a single command (used by REPEAT)."""
        lines = []
        if cmd.cmd_type == "string":
            escaped = self._escape_string(cmd.value)
            lines.append(f'typeString("{escaped}");')
        elif cmd.cmd_type == "stringln":
            escaped = self._escape_string(cmd.value)
            lines.append(f'typeString("{escaped}");')
            lines.append("bleKeyboard.press(KEY_RETURN);")
            lines.append("delay(10);")
            lines.append("bleKeyboard.release(KEY_RETURN);")
        elif cmd.cmd_type == "keypress":
            for key in cmd.keys:
                key_const = self._resolve_key(key)
                lines.append(f"bleKeyboard.press({key_const});")
            lines.append("delay(30);")
            for key in reversed(cmd.keys):
                key_const = self._resolve_key(key)
                lines.append(f"bleKeyboard.release({key_const});")
        elif cmd.cmd_type == "combo":
            for mod in cmd.modifiers:
                lines.append(f"bleKeyboard.press({BLE_MODIFIERS[mod]});")
            for key in cmd.keys:
                key_const = self._resolve_key(key)
                lines.append(f"bleKeyboard.press({key_const});")
            lines.append("delay(30);")
            for key in reversed(cmd.keys):
                key_const = self._resolve_key(key)
                lines.append(f"bleKeyboard.release({key_const});")
            for mod in reversed(cmd.modifiers):
                lines.append(f"bleKeyboard.release({BLE_MODIFIERS[mod]});")
        elif cmd.cmd_type == "delay":
            lines.append(f"delay({cmd.delay_ms});")
        return lines

    def _resolve_key(self, key: str) -> str:
        """Resolve a key name to its BLE Keyboard constant."""
        upper = key.upper()
        if upper in BLE_MODIFIERS:
            return BLE_MODIFIERS[upper]
        if upper in BLE_SPECIAL_KEYS:
            return BLE_SPECIAL_KEYS[upper]
        if len(key) == 1:
            return f"'{key}'"
        raise ValueError(f"Unknown key: {key}")

    def _escape_string(self, s: str) -> str:
        """Escape a string for C/Arduino."""
        return (
            s.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
